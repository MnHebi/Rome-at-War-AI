def patch():
    print('*** Begin Patch')
    for name, text in outputs().items():
        path = ROOT / name
        if not path.exists():
            print('*** Add File: ' + path.as_posix())
            print('\n'.join('+' + line for line in text.splitlines()))
        else:
            old = path.read_text(encoding='utf-8-sig')
            if old == text: continue
            print('*** Update File: ' + path.as_posix())
            for line in list(difflib.unified_diff(old.splitlines(), text.splitlines(), n=3))[2:]:
                print('@@' if line.startswith('@@') else line)
    print('*** End Patch')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        mismatches = [name for name, text in outputs().items()
                      if not (ROOT / name).exists() or (ROOT / name).read_text(encoding='utf-8-sig') != text]
        print('assault generation ' + ('FAIL: ' + ', '.join(mismatches) if mismatches else 'PASS'))
        raise SystemExit(bool(mismatches))
    patch()
