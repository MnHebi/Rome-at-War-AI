        # an idle hull at the eight-second sample cadence, not every rule sweep.
        out.append(rule([*sample, f'(up-compare-goal {v("state")} c:>= 1)',
                         f'(up-compare-goal {v("state")} c:<= 3)'], select()))
        out.append(rule([*sample, f'(up-compare-goal {v("state")} c:>= 1)',
            f'(up-compare-goal {v("state")} c:<= 3)', '(up-set-target-object search-local c: 0)',
            '(up-object-data object-data-idling == 1)'], [setv('issue', 1)]))
