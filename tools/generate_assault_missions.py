def fallback_enemy_scan():
    out = [';Generated bounded literal-player hostility gate. No engine enemy iterator.',
           ';The caller retains the original all-enemy waypoint AND landing danger scan.']
    scan = '(goal gl-transport-route-state TRANSPORT-ROUTE-UNSCREENED-SCAN)'
    out.append(rule([scan], ['(set-goal gl-assault-fallback-hostile NO)']))
    for p in range(1, 9):
        out.append(rule([scan, f'(goal gl-assault-fallback-player {p})',
                         f'(player-in-game {p})', f'(stance-toward {p} enemy)'],
                        ['(set-goal gl-assault-fallback-hostile YES)']))
    return '\n\n'.join(out) + '\n'


def preparation_ownership():
    """Guard acknowledged preparation leases, never the three dispatched slots.

    Only an idle, unowned original hull may be reclaimed for terminal recovery.
    A foreign/moving/attacked hull is left alone; the failed preparation releases
    only its own passenger flags. No STOP or retry loop is introduced.
    """
    out = [';Generated by tools/generate_assault_missions.py. T17 preparation lease guard.',
           ';Claim acknowledgement is in rawai-military.per. This catches later loss.',
           ';No active independent voyage is eligible for this handler.']
    kinds = (
        ('migration', 'gl-island-migration-state', 'gl-island-migration-transport-id',
         'migration-transport-group', 'migration-boarding-group', 'MIGRATION-',
         ['BOARDING', 'LOADING', 'CHECK-LOAD', 'ISSUE-BOARD', 'OWNERSHIP-CLAIM',
          'LOAD-DIAG-FIND', 'LOAD-DIAG-PASSENGER', 'LOAD-DIAG-APPLY',
          'ROUTE-PREPARE', 'ROUTE-LEFT', 'ROUTE-RIGHT', 'ROUTE-APPLY'],
         'gl-island-migration-origin-x', 'gl-island-migration-focus', 't-island-migration'),
        ('assault', 'gl-transport-route-state', 'gl-transport-route-id',
         'attack-transport-group', 'attack-boarding-group', 'TRANSPORT-ROUTE-',
         ['LOAD-SELECT', 'LOAD-ISSUE', 'LOAD-WAIT', 'LOAD-CHECK', 'LOAD-READY',
           'LOAD-DIAG-FIND', 'LOAD-DIAG-PASSENGER', 'LOAD-DIAG-APPLY', 'LOAD-PARTIAL-MANIFEST'],
         'gl-transport-route-origin-x', 'gl-transport-route-focus', 't-transport-route'))
    for kind, state, hull, group, passengers, prefix, phases, origin, focus, timer in kinds:
        facts = [f'(goal {state} {prefix}{phase})' for phase in phases]
        active = facts[-1]
        # Keep the identical binary OR tree, but never serialize the entire
        # expression onto a 600+ byte physical line (T17 startup ERR2005).
        for fact in reversed(facts[:-1]):
            active = f'(or {fact}\n\t\t' + active.replace('\n', '\n\t') + ')'
        lost = [f'(goal {state} {prefix}OWNER-LOST)']
        select = ['(up-full-reset-search)', f'(up-add-object-by-id search-local g: {hull})']
        owner = ['(up-set-target-object search-local c: 0)',
                 '(up-object-data object-data-player == my-player-number)',
                 f'(up-object-data object-data-group-flag == {group})']
        out.append(rule([active], ['(set-goal gl-transport-preparation-owned NO)', *select]))
        out.append(rule([active, *owner], ['(set-goal gl-transport-preparation-owned YES)']))
        out.append(rule([active, '(goal gl-transport-preparation-owned NO)'],
                        [f'(set-goal {state} {prefix}OWNER-LOST)']))
        out.append(rule(lost, [*select,
            f'(up-chat-data-to-all "RAW17 {kind} owner lost hull: %d" g: {hull})']))
        out.append(rule([*lost, '(up-set-target-object search-local c: 0)'], [
            '(up-get-object-data object-data-group-flag gl-transport-observed-value)',
            '(up-chat-data-to-all "RAW17 actual owner flag: %d" g: gl-transport-observed-value)',
            '(up-get-object-data object-data-order gl-transport-observed-value)',
            '(up-chat-data-to-all "RAW17 actual hull order: %d" g: gl-transport-observed-value)']))
        recover = [*lost, '(up-set-target-object search-local c: 0)',
                   '(up-object-data object-data-player == my-player-number)',
                   '(up-object-data object-data-group-flag < 0)',
                   '(up-object-data object-data-idling == 1)',
                   '(up-object-data object-data-under-attack == 0)']
        if kind == 'assault': recover += ['(goal gl-transport-route-script-load YES)']
        out.append(rule(recover, [
            '(up-remove-objects search-local object-data-player != my-player-number)',
            '(up-remove-objects search-local object-data-group-flag >= 0)',
            '(up-remove-objects search-local object-data-idling != 1)',
            '(up-remove-objects search-local object-data-under-attack > 0)',
            f'(up-create-group 0 0 c: {group})', f'(up-modify-group-flag 1 c: {group})']))
        recovery = [
            ';OWNERSHIP command: ' + group + '.',
            '(up-remove-objects search-local object-data-player != my-player-number)',
            f'(up-remove-objects search-local object-data-group-flag != {group})',
            f'(up-target-point {origin} action-unload -1 stance-no-attack)',
            f'(up-chat-data-to-all "RAW17 {kind} owner recovery hull: %d" g: {hull})',
            f'(up-modify-sn sn-focus-player-number g:= {focus})',
            f'(up-set-timer c: {timer} c: 15)']
        if kind == 'migration':
            recovery += ['(set-goal gl-island-migration-route-waits 0)',
                         '(set-goal gl-island-migration-rejection-armed NO)',
                         f'(set-goal {state} MIGRATION-RETURNING)']
        else:
            recovery += ['(set-goal gl-route-unload-attempts 0)',
                         f'(set-goal {state} TRANSPORT-ROUTE-RECOVERY-WAIT)']
        out.append(rule([*lost, *owner], recovery))
        out.append(rule(lost, [
            f'(up-chat-data-to-all "RAW17 {kind} owner yield hull: %d" g: {hull})',
            '(up-full-reset-search)', f'(up-set-group search-local c: {passengers})',
            '(up-remove-objects search-local object-data-player != my-player-number)',
            f'(up-remove-objects search-local object-data-group-flag != {passengers})',
            f'(up-create-group 0 0 c: {passengers})',
            f'(up-modify-group-flag 0 c: {passengers})', f'(up-reset-group c: {passengers})',
            f'(up-modify-sn sn-focus-player-number g:= {focus})',
            f'(up-set-timer c: {timer} c: 60)', f'(set-goal {state} {prefix}IDLE)']))
    return '\n\n'.join(out) + '\n'


